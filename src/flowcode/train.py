"""The training loop: rollouts in, one Tinker clock cycle out.

One step, in the order it happens and the order it must happen in:

1. **Sync the sampler** every ``train.sync_sampler_every`` steps, so rollouts come from
   something close to the current policy. (GFlowNet objectives do not *need* this — they
   are off-policy-consistent — but a sampler drifting arbitrarily far behind wastes the
   exploration budget on a policy nobody is training.)
2. **Roll out** ``groups_per_step`` prompts x ``group_size`` completions and score them.
3. **Mix in replay**, if enabled. The buffer is sampled *before* this step's rollouts are
   added to it, so replay is genuinely off-policy rather than partly a copy of the fresh
   batch.
4. **Get current-policy logprobs.** Either the ``forward()`` oracle
   (:meth:`~flowcode.tinker_backend.TinkerBackend.compute_logprobs`), or — under
   ``train.on_policy_only`` — the sampler's own logprobs, which skips a whole forward pass
   over every token in the batch and halves the training-token bill exactly.
5. **Loss and backward**, entirely client-side.
6. **Push the gradient, then step**, in that order and with ``defer=True``, so the
   ``forward_backward`` and the ``optim_step`` land in one server clock cycle instead of
   two. Reversing them, or draining the backward first, doubles the per-step latency for
   no other change.
7. **Step the local optimiser** for the objective's ``log Z`` / ``log F`` parameters. These
   live in this process (see :mod:`flowcode.objectives.flows`) and get their own Adam at
   ``train.flow_lr``, which is conventionally 100-1000x the policy LR.

``on_policy_only`` + ``replay.enabled`` is incoherent
-----------------------------------------------------
``on_policy_only`` means "the sampler's logprobs *are* the current policy's logprobs".
A replayed trajectory was generated by an older policy, so its stored logprobs are not the
current policy's and never will be. Training on them regresses the balance conditions
against the wrong ``log P_F``, which does not raise, does not look wrong in the metrics,
and quietly optimises the wrong thing. :func:`validate_train_config` rejects the
combination before a single dollar is spent.

Money
-----
The loop prints :func:`flowcode.cost.estimate` up front and
:func:`flowcode.cost.from_usage` at the end, and the final report is emitted from a
``finally``: a run that dies at step 700 of 1000 has still spent 70% of the estimate, and
that number must not die with the traceback.
"""

